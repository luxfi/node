func TestAddPermissionlessValidatorTx(t *testing.T) {
	var utxosOffset uint64 = 2025
	makeUTXO := func(amount uint64) *lux.UTXO {
		utxosOffset++
		return &lux.UTXO{
			UTXOID: lux.UTXOID{
				TxID:        ids.Empty.Prefix(utxosOffset),
				OutputIndex: uint32(utxosOffset),
			},
			Asset: lux.Asset{ID: utxoAssetID},
			Out: &secp256k1fx.TransferOutput{
				Amt:          amount,
				OutputOwners: utxoOwner,
			},
		}
	}

	var (
		utxos = []*lux.UTXO{
			makeUTXO(1 * constants.NanoLux), // small UTXO
			makeUTXO(9 * constants.Lux),     // large UTXO
		}

		validationRewardsOwner        = rewardsOwner
		delegationRewardsOwner        = rewardsOwner
		delegationShares       uint32 = reward.PercentDenominator
	)

	sk, err := localsigner.New()
	require.NoError(t, err)

	pop, err := signer.NewProofOfPossession(sk)
	require.NoError(t, err)

	for _, e := range testEnvironment {
		t.Run(e.name, func(t *testing.T) {
			var (
				require    = require.New(t)
				chainUTXOs = utxotest.NewDeterministicChainUTXOs(t, map[ids.ID][]*lux.UTXO{
					constants.PlatformChainID: utxos,
				})
				backend = wallet.NewBackend(chainUTXOs, nil)
				builder = builder.New(set.Of(utxoAddr, rewardAddr), e.context, backend)
			)

			utx, err := builder.NewAddPermissionlessValidatorTx(
				primaryNetworkPermissionlessStaker,
				pop,
				utxoAssetID,
				validationRewardsOwner,
				delegationRewardsOwner,
				delegationShares,
				common.WithMemo(e.memo),
			)
			require.NoError(err)
			require.Equal(primaryNetworkPermissionlessStaker.Validator, utx.Validator())
			require.Equal(primaryNetworkPermissionlessStaker.Chain, utx.Chain())
			// signer.ProofOfPossession carries a lazily-parsed `publicKey` that
			// Verify populates and that is NOT wire state. The round-tripped tx has
			// not called Verify, so comparing whole structs diffs on a cache field
			// while every wire byte matches. Compare the wire fields.
			gotPoP, ok := utx.Signer().(*signer.ProofOfPossession)
			require.True(ok, "signer is %T, want *signer.ProofOfPossession", utx.Signer())
			require.Equal(pop.PublicKey, gotPoP.PublicKey)
			require.Equal(pop.ProofOfPossession, gotPoP.ProofOfPossession)
			// Outputs should be merged if possible. For example, if there are two
			// unlocked inputs consumed for staking, this should only produce one staked
			// output.
			require.Len(utx.StakeOuts(), 1)
			// check stake amount
			require.Equal(
				map[ids.ID]uint64{
					utxoAssetID: primaryNetworkPermissionlessStaker.Wght,
				},
				addOutputAmounts(utx.StakeOuts()),
			)
			require.Equal(validationRewardsOwner, utx.ValidatorRewardsOwner())
			require.Equal(delegationRewardsOwner, utx.DelegatorRewardsOwner())
			require.Equal(delegationShares, utx.DelegationShares())
			require.Equal(e.memo, utx.Memo())
			requireFeeIsCorrect(
				require,
				e.feeCalculator,
				utx,
				nil,
				utx.StakeOuts(),
				nil,
			)
		})
	}
}

