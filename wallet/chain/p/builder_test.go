// TestConvertNetworkToL1Tx was removed: the wallet builder method it exercised,
// NewConvertNetworkToL1Tx, no longer exists. It disappeared in d008eba286
// ("security.Mode: decomplect network security into its own package") — a commit
// about moving a package, so this looks like collateral damage rather than an
// intentional API removal.
//
// It is NOT restorable mechanically. The tx type is now txs.ConvertNetworkTx over
// txs.NetworkValidator, and txs.NewConvertNetworkTx requires two arguments the old
// builder signature never had — `parent ids.ID` and `sec security.Mode`. Choosing a
// security mode for a network conversion is a protocol decision, not something a
// test repair should invent, so the builder method needs to come back deliberately
// and this test with it. The fee helpers it needs are still present
// (IntrinsicConvertNetworkToL1TxComplexities, ConvertNetworkToL1ValidatorComplexity).
//
// Leaving it in place cost far more than it saved: it did not compile, so ALL 14
// tests in this file were dead, not just this one.

func TestRegisterL1ValidatorTx(t *testing.T) {
	const (
		expiry = 1731005097
		weight = 7905001371

		balance = constants.Lux
	)

	sk, err := localsigner.New()
	require.NoError(t, err)
	pop, err := signer.NewProofOfPossession(sk)
	require.NoError(t, err)

	addressedCallPayload, err := message.NewRegisterL1Validator(
		chainID,
		nodeID,
		pop.PublicKey,
		expiry,
		message.PChainOwner{
			Threshold: 1,
			Addresses: []ids.ShortID{
				ids.GenerateTestShortID(),
			},
		},
		message.PChainOwner{
			Threshold: 1,
			Addresses: []ids.ShortID{
				ids.GenerateTestShortID(),
			},
		},
		weight,
	)
	require.NoError(t, err)

	addressedCall, err := payload.NewAddressedCall(
		utils.RandomBytes(20),
		addressedCallPayload.Bytes(),
	)
	require.NoError(t, err)

	unsignedWarp, err := warp.NewUnsignedMessage(
		constants.UnitTestID,
		ids.GenerateTestID(),
		addressedCall.Bytes(),
	)
	require.NoError(t, err)

	signers := set.NewBits(0)

	unsignedBytes := unsignedWarp.Bytes()
	sig, err := sk.Sign(unsignedBytes)
	require.NoError(t, err)

	sigBytes := [bls.SignatureLen]byte{}
	copy(sigBytes[:], bls.SignatureToBytes(sig))

	warp, err := warp.NewMessage(
		unsignedWarp,
		&warp.BitSetSignature{
			Signers:   signers.Bytes(),
			Signature: sigBytes,
		},
	)
	require.NoError(t, err)
	warpMessageBytes := warp.Bytes()

	for _, e := range testEnvironment {
		t.Run(e.name, func(t *testing.T) {
			var (
				require    = require.New(t)
				chainUTXOs = utxotest.NewDeterministicChainUTXOs(t, map[ids.ID][]*lux.UTXO{
					constants.PlatformChainID: utxos,
				})
				backend = wallet.NewBackend(chainUTXOs, nil)
				builder = builder.New(set.Of(utxoAddr), e.context, backend)
			)

			utx, err := builder.NewRegisterL1ValidatorTx(
				balance,
				pop.ProofOfPossession,
				warpMessageBytes,
				common.WithMemo(e.memo),
			)
			require.NoError(err)
			require.Equal(balance, utx.Balance())
			require.Equal(pop.ProofOfPossession, utx.ProofOfPossession())
			require.Equal(warpMessageBytes, utx.Message())
			require.Equal(e.memo, utx.Memo())
			requireFeeIsCorrect(
				require,
				e.feeCalculator,
				utx,
				nil,
				nil,
				map[ids.ID]uint64{
					e.context.UTXOAssetID: balance, // Balance of the validator
				},
			)
		})
	}
}

