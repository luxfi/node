func TestIncreaseL1ValidatorBalanceTxSyntacticVerify(t *testing.T) {
	var (
		rt         = consensustest.Runtime(t, ids.GenerateTestID())
		validBaseTx = BaseTx{
			BaseTx: lux.BaseTx{
				NetworkID:    rt.NetworkID,
				BlockchainID: rt.ChainID,
			},
		}
	)
	tests := []struct {
		name        string
		tx          *IncreaseL1ValidatorBalanceTx
		expectedErr error
	}{
		{
			name:        "nil tx",
			tx:          nil,
			expectedErr: ErrNilTx,
		},
		{
			name: "already verified",
			// The tx includes invalid data to verify that a cached result is
			// returned.
			tx: &IncreaseL1ValidatorBalanceTx{
				BaseTx: BaseTx{
					SyntacticallyVerified: true,
				},
				Balance: 0,
			},
			expectedErr: nil,
		},
		{
			name: "zero balance",
			tx: &IncreaseL1ValidatorBalanceTx{
				BaseTx:  validBaseTx,
				Balance: 0,
			},
			expectedErr: ErrZeroBalance,
		},
		{
			name: "invalid BaseTx",
			tx: &IncreaseL1ValidatorBalanceTx{
				BaseTx:  BaseTx{},
				Balance: 1,
			},
			expectedErr: lux.ErrWrongNetworkID,
		},
		{
			name: "passes verification",
			tx: &IncreaseL1ValidatorBalanceTx{
				BaseTx:  validBaseTx,
				Balance: 1,
			},
			expectedErr: nil,
		},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			require := require.New(t)

			err := test.tx.SyntacticVerify(rt)
			require.ErrorIs(err, test.expectedErr)
			if test.expectedErr != nil {
				return
			}
			require.True(test.tx.SyntacticallyVerified)
		})
	}
}
